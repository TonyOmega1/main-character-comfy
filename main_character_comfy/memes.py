"""The meme format library for **Meme Recreate**.

Formats live in ``formats/memes.json`` (plus any ``formats/community/*.json``)
so the community can add or tweak them with a pull request, no Python needed.

Every entry is an *original recipe*: a description of a generic, widely used
reaction-video format (a gesture, a camera move, a caption layout) written from
scratch for MC. Nothing in it contains, references or reproduces any
specific photo, video, frame, character or real person. The user's own photo is
the only subject; the scene is newly generated by FLUX.2 klein and the motion
by Wan 2.2, so every output is a new clip, not a copy of existing footage.
"""

from __future__ import annotations

import json
import os
import random
import re
from dataclasses import dataclass, field
from pathlib import Path

FORMATS_DIR = Path(__file__).parent / "formats"


def community_dir() -> Path:
    """Where "Save as format" writes (and where community formats are loaded from)."""
    return Path(os.environ.get("MC_COMMUNITY_DIR") or FORMATS_DIR / "community")
EFFECTS = ("none", "punch_in", "shake", "boomerang")
# Where the meme captions go. ``classic``: top + bottom. ``edges``: smaller and pushed to the very top/bottom
# edges (for crash zooms, where the face fills the middle). ``top``: both lines stacked at the top (for
# formats where the body/action fills the lower half, e.g. a dance).
CAPTION_LAYOUTS = ("classic", "edges", "top")
VIBES = ("reaction", "chaos", "smug", "panic", "wholesome")


@dataclass(frozen=True)
class MemeRecipe:
    key: str
    label: str
    emoji: str
    scene: str  # FLUX.2 klein edit: where the user is, pose, framing, wardrobe, lighting
    motion: str  # Wan 2.2 I2V: the action and camera move
    camera: str  # human-readable shot note (also appended to the motion prompt)
    top: str = ""  # default top caption (= captions[0])
    bottom: str = ""
    line: str = ""  # optional spoken line -> InfiniteTalk lip sync in the user's voice
    effect: str = "none"  # post effect in the finisher (local ffmpeg)
    effect_at: float = 0.0  # seconds into the clip
    frames: int = 81  # ~5 s at 16 fps
    vibe: str = "reaction"
    captions: tuple[tuple[str, str], ...] = field(default_factory=tuple)  # swappable (top, bottom) pairs
    fresh: bool = False
    negative: str = ""  # extra Wan negative terms for this format (e.g. "hand entering the frame")
    caption_layout: str = "classic"  # see CAPTION_LAYOUTS

    @property
    def title(self) -> str:
        return f"{self.emoji} {self.label}"


def _from_dict(d: dict) -> MemeRecipe:
    r = _from_dict_unchecked(d)
    problems = check_recipe(r)
    if problems:
        raise ValueError(f"format '{r.key}': " + "; ".join(problems))
    return r


def _from_dict_unchecked(d: dict) -> MemeRecipe:
    caps = tuple((c.get("top", ""), c.get("bottom", "")) for c in d.get("captions", []))
    if not caps:
        caps = ((d.get("top", ""), d.get("bottom", "")),)
    r = MemeRecipe(
        key=d["key"], label=d["label"], emoji=d.get("emoji", "🙂"), scene=d["scene"], motion=d["motion"],
        camera=d.get("camera", "static camera"), top=caps[0][0], bottom=caps[0][1], line=d.get("line", ""),
        effect=d.get("effect", "none"), effect_at=float(d.get("effect_at", 0.0)), frames=int(d.get("frames", 81)),
        vibe=d.get("vibe", "reaction"), captions=caps, fresh=bool(d.get("fresh", False)),
        negative=d.get("negative", ""), caption_layout=d.get("caption_layout", "classic"),
    )
    return r


def check_recipe(r: MemeRecipe) -> list[str]:
    """Structural rules every format file must pass (also enforced by the tests)."""
    p = []
    if "image 1" not in r.scene:
        p.append("scene must refer to the user's photo as 'image 1'")
    if r.effect not in EFFECTS:
        p.append(f"effect must be one of {EFFECTS}")
    if r.vibe not in VIBES:
        p.append(f"vibe must be one of {VIBES}")
    if r.frames % 4 != 1 or not 17 <= r.frames <= 121:
        p.append("frames must be 4n+1 between 17 and 121")
    if r.caption_layout not in CAPTION_LAYOUTS:
        p.append(f"caption_layout must be one of {CAPTION_LAYOUTS}")
    if len(r.negative) > 200:
        p.append("negative must be under 200 characters")
    if len(r.line) > 200:
        p.append("line must be under 200 characters")
    if any(len(t) > 60 or len(b) > 60 for t, b in r.captions):
        p.append("captions must be under 60 characters each")
    return p


def load_library(paths: list[Path] | None = None, strict: bool = False) -> dict[str, MemeRecipe]:
    """Built-in formats first, then community files (later files override by key).
    The built-in file must be valid; a broken community file is skipped with a
    warning instead of taking the whole app down (``strict`` raises instead)."""
    if paths is None:
        paths = [FORMATS_DIR / "memes.json", *sorted(community_dir().glob("*.json"))]
        extra = os.environ.get("MC_FORMATS")
        if extra:
            paths.append(Path(extra))
    lib: dict[str, MemeRecipe] = {}
    for n, path in enumerate(paths):
        try:
            doc = json.loads(Path(path).read_text(encoding="utf-8"))
            items = [_from_dict(d) for d in doc.get("formats", doc if isinstance(doc, list) else [])]
        except (ValueError, KeyError, TypeError, OSError) as exc:
            if strict or n == 0:
                raise
            print(f"[mc] skipping format file {path}: {exc}")
            continue
        for r in items:
            lib[r.key] = r
    return lib


RECIPES: dict[str, MemeRecipe] = load_library()
BUILTIN_KEYS = frozenset(load_library([FORMATS_DIR / "memes.json"]))
DEFAULT_RECIPE = "side_eye"


def reload() -> dict[str, MemeRecipe]:
    """Re-read the library in place (other modules hold a reference to RECIPES)."""
    fresh = load_library()
    RECIPES.clear()
    RECIPES.update(fresh)
    return RECIPES


def recipe_to_dict(r: MemeRecipe) -> dict:
    return {"key": r.key, "label": r.label, "emoji": r.emoji, "vibe": r.vibe, "scene": r.scene, "motion": r.motion,
            "camera": r.camera, "line": r.line, "effect": r.effect, "effect_at": r.effect_at, "frames": r.frames,
            "captions": [{"top": t, "bottom": b} for t, b in r.captions], "fresh": r.fresh,
            **({"negative": r.negative} if r.negative else {}),
            **({"caption_layout": r.caption_layout} if r.caption_layout != "classic" else {})}


def _slug_key(name: str) -> str:
    key = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")[:40]
    return key or "my_format"


def save_format(recipe: MemeRecipe | dict, name: str, *, emoji: str = "", captions: list[tuple[str, str]] | None = None,
                directory: Path | None = None, source: str = "") -> tuple[str, Path]:
    """**Save as format**: write ``recipe`` as a reusable community format JSON and
    reload the library so it shows up in the format grid right away.

    ``captions`` (e.g. the ones on your finished meme) go first. Built-in keys are
    never overwritten; a clashing name gets a numbered key. Returns (key, path)."""
    from .safety import is_sfw

    d = dict(recipe_to_dict(recipe) if isinstance(recipe, MemeRecipe) else recipe)
    name = (name or "").strip() or d.get("label", "") or "My format"
    if len(name) > 40:
        raise ValueError("Keep the format name under 40 characters.")
    caps: list[tuple[str, str]] = []
    for t, b in [*(captions or []), *((c["top"], c["bottom"]) for c in d.get("captions", []))]:
        pair = ((t or "").strip(), (b or "").strip())
        if any(pair) and pair not in caps:
            caps.append(pair)
    caps = caps[:6] or [("", "")]
    if not is_sfw(name, d.get("scene"), d.get("motion"), d.get("line"), *[x for p in caps for x in p]):
        raise ValueError("Formats are SFW only.")
    folder = Path(directory or community_dir())
    folder.mkdir(parents=True, exist_ok=True)
    base = _slug_key(name)
    key, i = base, 2
    while key in BUILTIN_KEYS or (folder / f"{key}.json").exists():
        key, i = f"{base}_{i}", i + 1
    d.update(key=key, label=name, emoji=(emoji or d.get("emoji") or "⭐")[:4],
             captions=[{"top": t, "bottom": b} for t, b in caps], fresh=True)
    d.pop("top", None)
    d.pop("bottom", None)
    problems = check_recipe(_from_dict_unchecked(d))
    if problems:
        raise ValueError("Can't save this format: " + "; ".join(problems))
    doc = {"$comment": "Saved with MC 'Save as format'. Original recipes only: no real people, no "
                       "copyrighted characters or footage. Share it by opening a pull request.",
           "version": 1, "source": source, "formats": [d]}
    path = folder / f"{key}.json"
    path.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    if directory is None or Path(directory) == community_dir():
        reload()
    return key, path

_KEEP = ("Keep the person's exact face, identity, hairstyle, skin tone and body shape from image 1. "
         "Photorealistic, natural skin texture, vertical 9:16 frame, no text, no captions, no watermark, "
         "the person is the only person in the frame.")


# Avatar mode: the upload is a character (cartoon, anime, 3D, VTuber, pixel art, mascot, non-human...),
# so keep ITS art style instead of turning it into a photo.
AVATAR_KEEP = ("The person in image 1 is a stylized character: keep that exact character design, art style, "
               "rendering technique, proportions, colors, outfit and any non-human features exactly as drawn in "
               "image 1, and render the whole scene in that same art style, not photorealistic. "
               "Vertical 9:16 frame, no text, no captions, no watermark, the character is the only one in the frame.")
AVATAR_MOTION = "Smooth natural motion, the character keeps its exact design, colors and art style in every frame."


def edit_prompt(recipe: MemeRecipe, style_hint: str = "", subject: str = "photo") -> str:
    """FLUX.2 klein reference-edit prompt that places the user (or their avatar) in the recipe's scene."""
    if subject == "avatar":
        keep = AVATAR_KEEP if not style_hint else f"{AVATAR_KEEP} {style_hint}."
    else:
        keep = _KEEP if not style_hint else _KEEP.replace("Photorealistic, natural skin texture", style_hint)
    return f"{recipe.scene} {keep}"


def motion_prompt(recipe: MemeRecipe, talking: bool = False, subject: str = "photo") -> str:
    who = "The character" if subject == "avatar" else "The person"
    talk = f" {who} talks to the camera with natural expressive lip movements." if talking else ""
    tail = AVATAR_MOTION if subject == "avatar" else "Smooth natural motion, consistent face and identity."
    return f"{recipe.motion}{talk} {recipe.camera}. {tail}"


def custom_recipe(scene: str, motion: str, top: str = "", bottom: str = "", line: str = "") -> MemeRecipe:
    """User-written format (same compliance rules apply: no real people, no copied footage)."""
    return MemeRecipe("custom", "Custom format", "✍️", f"Put the person from image 1 in this scene: {scene.strip()}",
                      motion.strip(), "static camera", top, bottom, line, captions=((top, bottom),))


def next_caption(key: str, current: tuple[str, str] | None = None, rng: random.Random | None = None) -> tuple[str, str]:
    """🎲 caption: a different pre-written pair for this format."""
    r = RECIPES.get(key)
    if r is None or not r.captions:
        return current or ("", "")
    pool = [c for c in r.captions if c != current] or list(r.captions)
    return (rng or random).choice(pool)


def surprise(rng: random.Random | None = None) -> tuple[str, tuple[str, str]]:
    """Random format + random caption."""
    rng = rng or random
    key = rng.choice(list(RECIPES))
    return key, rng.choice(RECIPES[key].captions)
